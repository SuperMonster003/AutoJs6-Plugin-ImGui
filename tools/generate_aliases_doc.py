#!/usr/bin/env python3
"""Regenerate or verify the PascalCase alias list in docs/ALIASES.md from the plugin facade."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
FACADE_PATH = REPOSITORY_ROOT / "app/src/main/assets/plugin/index.js"
IMGUI_HEADER_PATH = REPOSITORY_ROOT / "app/src/main/cpp/third_party/imgui/imgui.h"
DOCUMENT_PATH = REPOSITORY_ROOT / "docs/ALIASES.md"
BEGIN_MARKER = "<!-- aliases:begin (generated by tools/generate_aliases_doc.py) -->"
END_MARKER = "<!-- aliases:end -->"


def read_aliases() -> list[tuple[str, str]]:
    source = FACADE_PATH.read_text(encoding="utf-8")
    block = re.search(r"\n\s*var aliases = \{\n(.*?)\n\s*\};", source, re.S)
    if block is None:
        raise SystemExit(f"{FACADE_PATH}: alias table not found")
    aliases = re.findall(r"^\s*(\w+): \"(\w+)\",?$", block.group(1), re.M)
    if len(aliases) != len([line for line in block.group(1).splitlines() if line.strip()]):
        raise SystemExit(f"{FACADE_PATH}: alias table has lines that are not 'Alias: \"target\"'")
    return aliases


def read_upstream_functions() -> tuple[set[str], set[str]]:
    """Return the ImGui:: functions of imgui.h and those it lists only under its obsolete section."""
    header = IMGUI_HEADER_PATH.read_text(encoding="utf-8")
    namespaces = re.findall(r"\nnamespace ImGui\n\{\n(.*?)\n\}", header, re.S)
    if len(namespaces) != 2:
        raise SystemExit(f"{IMGUI_HEADER_PATH}: expected the main and the obsolete namespace ImGui blocks")
    current, obsolete = (set(re.findall(r"IMGUI_API\s[^;(]*?\b(\w+)\(", block)) for block in namespaces)
    return current, obsolete - current


def render(aliases: list[tuple[str, str]], upstream: tuple[set[str], set[str]]) -> str:
    current, obsolete = upstream

    def upstream_cell(alias: str) -> str:
        if alias in current:
            return f"`ImGui::{alias}`"
        if alias in obsolete:
            return f"`ImGui::{alias}` (obsolete)"
        return "-"

    unmatched = [alias for alias, _ in aliases if upstream_cell(alias) == "-"]
    lines = [
        BEGIN_MARKER,
        "",
        f"{len(aliases)} aliases, in the order of the facade's alias table. \"Upstream\" is the `ImGui::` function of the",
        "same name in the vendored `imgui.h`, marked \"obsolete\" when the header lists it only as an obsolete function.",
        f"The {len(unmatched)} aliases marked \"-\" name plugin features or differ from the upstream name (see \"Names\" above).",
        "",
        "| Alias | Target | Upstream |",
        "| --- | --- | --- |",
    ]
    for alias, target in aliases:
        lines.append(f"| `{alias}` | `{target}` | {upstream_cell(alias)} |")
    lines += ["", END_MARKER]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when docs/ALIASES.md is out of date")
    arguments = parser.parse_args()

    document = DOCUMENT_PATH.read_text(encoding="utf-8")
    start = document.find(BEGIN_MARKER)
    end = document.find(END_MARKER)
    if start < 0 or end < start:
        raise SystemExit(f"{DOCUMENT_PATH}: generated section markers not found")
    generated = render(read_aliases(), read_upstream_functions())
    updated = document[:start] + generated + document[end + len(END_MARKER):]
    if updated == document:
        print(f"{DOCUMENT_PATH.relative_to(REPOSITORY_ROOT)} is up to date")
        return 0
    if arguments.check:
        print(f"{DOCUMENT_PATH.relative_to(REPOSITORY_ROOT)} is out of date; run python tools/generate_aliases_doc.py")
        return 1
    DOCUMENT_PATH.write_text(updated, encoding="utf-8", newline="\n")
    print(f"Updated {DOCUMENT_PATH.relative_to(REPOSITORY_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
